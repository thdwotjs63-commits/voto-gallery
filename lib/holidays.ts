/** 요일 기반 주말 판정: 0=일, 6=토 */
export function getDayType(dateStr: string): "sun" | "sat" | "weekday" {
  const dt = new Date(dateStr + "T00:00:00");
  const d = dt.getDay();
  if (d === 0) return "sun";
  if (d === 6) return "sat";
  return "weekday";
}
